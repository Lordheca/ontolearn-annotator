"""epp_dataset dataset."""

import csv
import hashlib
import random
from collections import defaultdict
from pathlib import Path

import tensorflow as tf
import tensorflow_datasets as tfds
from PIL import Image

DATASET_DIR = Path(__file__).resolve().parent
DATA_DIR = DATASET_DIR / "data"
IMAGES_DIR = DATA_DIR / "images"
CLASSES_FILE = DATASET_DIR / "classes.csv"
MASTER_CSV = DATA_DIR / "5k_epp_dataset.csv"

SPLIT_SEED = 42
TEST_FRACTION = 0.1
VALIDATION_FRACTION = 0.1


def load_classes(path: Path = CLASSES_FILE):
    """Read the class list (``code;name_en;name_ja``) in file order.

    The order defines the label index the model is trained on, so this file
    (generated by ``prepare_labels.py``) is the single source of truth for the
    classes. Changing the taxonomy means regenerating it, not editing code.
    """
    with open(path, newline="", encoding="utf-8") as f:
        classes = list(csv.DictReader(f, delimiter=";"))
    if not classes:
        raise ValueError(f"No classes found in {path}")
    codes = [c["code"] for c in classes]
    if len(codes) != len(set(codes)):
        raise ValueError(f"Duplicate class codes in {path}")
    return classes


def _read_csv(path: Path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f, delimiter=";")
        return reader.fieldnames, list(reader)


def _write_csv(path: Path, fieldnames, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, delimiter=";")
        writer.writeheader()
        writer.writerows(rows)


class Builder(tfds.core.GeneratorBasedBuilder):
    """DatasetBuilder for 5K EPP Water Crystal dataset."""

    VERSION = tfds.core.Version("2.0.0")
    RELEASE_NOTES = {
        "1.0.0": "Initial release (13 hard-coded classes).",
        "2.0.0": "Classes read from classes.csv (26 hierarchical EPP labels); stratified split.",
    }

    def _info(self) -> tfds.core.DatasetInfo:
        """Returns the dataset metadata."""
        return self.dataset_info_from_configs(
            features=tfds.features.FeaturesDict(
                {
                    "image": tfds.features.Image(shape=(240, 360, 3)),
                    # Label names are the class codes ("1.1", "1.7.3", ...);
                    # display names live in classes.csv.
                    "label": tfds.features.ClassLabel(
                        names=[c["code"] for c in load_classes()]
                    ),
                }
            ),
            supervised_keys=("image", "label"),
            homepage="https://ieee-dataport.org/documents/5k-epp-water-crystal-dataset",
        )

    def _split_generators(self, dl_manager: tfds.download.DownloadManager):
        """Returns SplitGenerators."""
        return {
            "train": self._generate_examples(label_path=DATA_DIR / "train_labels.csv"),
            "test": self._generate_examples(label_path=DATA_DIR / "test_labels.csv"),
            "validation": self._generate_examples(label_path=DATA_DIR / "validation_labels.csv"),
        }

    def _initalize_dataset(self):
        print("Label file not found, separating CSV into 3 files")

        # Resize all images to 360 * 240
        image_files = [f for f in tf.io.gfile.listdir(IMAGES_DIR) if f.endswith(".jpg")]
        for image_file in image_files:
            image_path = IMAGES_DIR / image_file
            with Image.open(image_path) as image:
                resized_image = image.resize((360, 240))
            resized_image.save(image_path)

        # Find identical images by checksum and keep only one of each
        file_hashes = {}
        duplicates = []
        for image_file in sorted(tf.io.gfile.listdir(IMAGES_DIR)):
            with open(IMAGES_DIR / image_file, "rb") as f:
                file_hash = hashlib.md5(f.read()).hexdigest()
            if file_hash in file_hashes:
                duplicates.append(image_file)
            else:
                file_hashes[file_hash] = image_file
        for image_file in duplicates:
            tf.io.gfile.remove(IMAGES_DIR / image_file)

        # Drop rows for duplicates, missing images and unknown labels
        known_codes = {c["code"] for c in load_classes()}
        fieldnames, rows = _read_csv(MASTER_CSV)
        removed = set(duplicates)
        kept = []
        for row in rows:
            if row["image_name"] in removed:
                continue
            if not tf.io.gfile.exists(IMAGES_DIR / row["image_name"]):
                print(f"Missing image, skipped: {row['image_name']}")
                continue
            if row["label"] not in known_codes:
                print(f"Unknown label {row['label']!r}, skipped: {row['image_name']}")
                continue
            kept.append(row)
        # Never overwrite the master CSV: the split files are enough, and a bad
        # images folder must not destroy the label list.
        print(f"Kept {len(kept)} of {len(rows)} rows ({len(rows) - len(kept)} dropped)")
        if len(kept) < 0.9 * len(rows):
            raise RuntimeError(
                f"Only {len(kept)} of {len(rows)} labelled rows have an image in "
                f"{IMAGES_DIR}. Check the images folder; no split files were written."
            )

        # Stratified 80/10/10 split: every class keeps the same proportions in
        # each split, so rare classes are not left out of train by chance.
        # Classes with fewer than 3 images go entirely to train.
        by_label = defaultdict(list)
        for row in kept:
            by_label[row["label"]].append(row)

        rng = random.Random(SPLIT_SEED)
        train_rows, test_rows, validation_rows = [], [], []
        for label in sorted(by_label):
            group = by_label[label]
            rng.shuffle(group)
            if len(group) < 3:
                n_test = n_validation = 0
            else:
                n_test = max(1, round(len(group) * TEST_FRACTION))
                n_validation = max(1, round(len(group) * VALIDATION_FRACTION))
            test_rows += group[:n_test]
            validation_rows += group[n_test:n_test + n_validation]
            train_rows += group[n_test + n_validation:]

        for split_rows in (train_rows, test_rows, validation_rows):
            rng.shuffle(split_rows)

        print(
            f"Total: {len(kept)}, Train: {len(train_rows)}, "
            f"Test: {len(test_rows)}, Validation: {len(validation_rows)}"
        )
        _write_csv(DATA_DIR / "train_labels.csv", fieldnames, train_rows)
        _write_csv(DATA_DIR / "test_labels.csv", fieldnames, test_rows)
        _write_csv(DATA_DIR / "validation_labels.csv", fieldnames, validation_rows)

    def _generate_examples(self, label_path):
        """Yields examples."""
        # Split the master CSV into 3 files the first time
        if not label_path.exists():
            self._initalize_dataset()

        known_codes = {c["code"] for c in load_classes()}
        _, rows = _read_csv(label_path)
        for row in rows:
            if row["label"] not in known_codes:
                raise ValueError(
                    f"{label_path.name}: label {row['label']!r} of {row['image_name']} "
                    f"is not in {CLASSES_FILE.name}. Delete the *_labels.csv files to re-split."
                )
            image_id = row["image_name"]
            yield image_id, {
                "label": row["label"],
                "image": str(IMAGES_DIR / image_id),
            }
